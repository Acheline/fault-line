def load_real_graph():
    """
    Read the real dependency graph generated by the teammate.

    Supports both dictionary and list formats for nodes and edges.
    Returns None if hero1.json cannot be found.
    """

    if not REAL_GRAPH_PATH.exists():
        return None

    with open(
        REAL_GRAPH_PATH,
        "r",
        encoding="utf-8"
    ) as f:
        raw = json.load(f)

    # ========================================================
    # NODES
    # ========================================================

    raw_nodes = raw.get("nodes", {})

    if isinstance(raw_nodes, dict):
        node_items = raw_nodes.items()
    else:
        node_items = [
            (node.get("id"), node)
            for node in raw_nodes
        ]

    nodes = []

    for node_id, node in node_items:

        if not isinstance(node, dict):
            continue

        nodes.append({
            "id": node_id,
            "label": node.get(
                "label",
                node_id
            ),
            "type": node.get(
                "type",
                "UNKNOWN"
            ),
            "address": node.get(
                "address"
            ),
            "chain": node.get(
                "chain"
            ),
            "paths": node.get(
                "paths",
                []
            ),
            "tags": node.get(
                "tags",
                []
            ),
            "props": node.get(
                "props",
                {}
            ),
            "provenance": node.get(
                "provenance",
                []
            )
        })

    # ========================================================
    # EDGES
    # ========================================================

    raw_edges = raw.get(
        "edges",
        {}
    )

    if isinstance(raw_edges, dict):
        edge_items = raw_edges.values()
    else:
        edge_items = raw_edges

    edges = []

    for edge in edge_items:

        if not isinstance(edge, dict):
            continue

        source = (
            edge.get("src")
            or edge.get("source")
        )

        target = (
            edge.get("dst")
            or edge.get("target")
        )

        if source is None or target is None:
            continue

        edges.append({
            "source": source,
            "target": target,
            "type": edge.get(
                "type",
                ""
            ),
            "props": edge.get(
                "props",
                {}
            ),
            "provenance": edge.get(
                "provenance",
                []
            )
        })

    # ========================================================
    # FINAL NORMALIZED GRAPH
    # ========================================================

    return {
        "position_id": raw.get(
            "position_id"
        ),
        "fork_block": raw.get(
            "fork_block"
        ),
        "nodes": nodes,
        "edges": edges,
        "meta": raw.get(
            "meta",
            {}
        )
    }

