# ============================================================
# RISK CALCULATIONS
# Still based on temporary scenario assumptions.
# ============================================================

def calculate_metrics(
    position_size,
    scenario,
    probability,
    risk_aversion
):

    scale = position_size / BASE_POSITION_SIZE

    position_after = (
        scenario["position_after"]
        * scale
    )

    exit_proceeds = (
        scenario["exit_proceeds"]
        * scale
    )

    scenario_loss = (
        position_size
        - position_after
    )

    exit_cost = (
        position_size
        - exit_proceeds
    )

    expected_loss = (
        probability
        * scenario_loss
    )

    np.random.seed(
        RANDOM_SEED
    )

    incident = (
        np.random.random(
            N_SIMULATIONS
        )
        < probability
    )

    severity = np.random.normal(
        1.0,
        0.20,
        N_SIMULATIONS
    )

    severity = np.clip(
        severity,
        0.25,
        1.75
    )

    losses = np.where(
        incident,
        scenario_loss * severity,
        0
    )

    losses = np.clip(
        losses,
        0,
        position_size
    )

    mc_expected_loss = float(
        np.mean(losses)
    )

    var95 = float(
        np.quantile(
            losses,
            0.95
        )
    )

    tail = losses[
        losses >= var95
    ]

    cvar95 = (
        float(np.mean(tail))
        if len(tail) > 0
        else 0
    )

    risk_adjusted = (
        mc_expected_loss
        + risk_aversion
        * max(
            0,
            cvar95 - mc_expected_loss
        )
    )

    if mc_expected_loss >= exit_cost:
        recommendation = "EXIT"

    elif risk_adjusted >= exit_cost:
        recommendation = "REDUCE"

    else:
        recommendation = "STAY"

    breakeven = (
        exit_cost / scenario_loss
        if scenario_loss > 0
        else 0
    )

    return {
        "position_after": position_after,
        "exit_proceeds": exit_proceeds,
        "scenario_loss": scenario_loss,
        "exit_cost": exit_cost,
        "expected_loss": expected_loss,
        "mc_expected_loss": mc_expected_loss,
        "var95": var95,
        "cvar95": cvar95,
        "risk_adjusted": risk_adjusted,
        "recommendation": recommendation,
        "breakeven": breakeven,
        "losses": losses
    }